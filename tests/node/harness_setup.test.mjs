function withInternals(replacements, body) {
  const saved = { ...harness.internals };
  Object.assign(harness.internals, replacements);
  try {
    return body();
  } finally {
    Object.assign(harness.internals, saved);
  }
}

test('an installer without a #! line fails like execve, never runs, and the package is rolled back', { skip: skipOnWindows('the fake omp installer is a #! shell script (execve/ENOEXEC and /bin/sh text-mode output); Windows runs omp.exe') }, (t) => {
  const { root, home, release, state } = fixture(t);
  const omp = nat(`${root}/omp`);
  writeFileSync(omp, `touch '${root}/ran'\n`);
  chmodSync(omp, 0o755);
  assert.throws(() => withInternals({ which: () => omp }, () => harness.configure_omp(home, state.command, release,
    { scope: 'user', project: null, env: { PATH: '/bin', HOME: home } })), { message: `[Errno 8] Exec format error: '${omp}'` });
  assert.equal(existsSync(nat(`${root}/ran`)), false);
  assert.deepEqual(readdirSync(nat(`${home}/.local/share/lcu/omp`)), []);
});

test('installer diagnostics get Python text-mode newlines', { skip: skipOnWindows('the fake omp installer is a #! shell script (execve/ENOEXEC and /bin/sh text-mode output); Windows runs omp.exe') }, (t) => {
  const { root, home, release, state } = fixture(t);
  const omp = nat(`${root}/omp`);
  writeFileSync(omp, "#!/bin/sh\nprintf 'line1\\r\\nline2\\rline3\\n' >&2\nexit 9\n");
  chmodSync(omp, 0o755);
  assert.throws(() => withInternals({ which: () => omp }, () => harness.configure_omp(home, state.command, release,
    { scope: 'user', project: null, env: { PATH: '/bin', HOME: home } })), { message: 'installer exited 9: line1\nline2\nline3' });
});

test('Windows paths: drive-absolute HERMES_HOME, rooted-only and relative profiles (fixture, no live Windows)', () => {
  withInternals({ platform: 'win32', which: () => 'C:\\bin\\hermes.exe' }, () => {
    const call = (profile) => harness.configure_hermes('C:\\Users\\fixture', ['lcu'], 'C:\\node.exe', 'C:\\lcu',
      { scope: 'user', project: null, env: { PATH: 'C:\\bin', HERMES_HOME: profile } });
    // Accepted as absolute: fails only later, at the (absent) release files, with WindowsPath joins.
    assert.throws(() => call('C:\\profiles\\hermes'), { message: 'LCU Hermes plugin missing: C:\\lcu\\adapters\\hermes\\plugin.yaml' });
    assert.throws(() => call('\\\\server\\share\\hermes'), { message: /^LCU Hermes plugin missing/ });
    for (const profile of ['\\profiles\\hermes', 'profiles\\hermes', 'C:profiles']) {
      assert.throws(() => call(profile), { message: 'HERMES_HOME must be absolute.' });
    }
  });
});

