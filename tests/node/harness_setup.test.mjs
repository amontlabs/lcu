const harness = await lcu('harness_setup');

function walk(root, prefix = '') {
  const out = {};
  for (const entry of readdirSync(`${root}/${prefix}`, { withFileTypes: true })) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) Object.assign(out, walk(root, relative));
    else if (statSync(`${root}/${relative}`).isFile()) out[relative] = readFileSync(`${root}/${relative}`).toString('hex');
  }
  return out;
}

function fixture(t) {
  const root = tempdir(t);
  const home = nat(`${root}/home`);
  mkdirSync(home);
  const project = nat(`${root}/project with spaces`);
  mkdirSync(project);
  const release = nat(`${root}/release`);
  mkdirSync(nat(`${release}/adapters/pi`), { recursive: true });
  writeFileSync(nat(`${release}/adapters/pi/index.ts`), 'export default function () {}');
  mkdirSync(nat(`${release}/adapters/hermes`));
  for (const name of ['plugin.yaml', '__init__.py', 'bridge.mjs']) writeFileSync(`${release}/adapters/hermes/${name}`, 'fixture ' + name);
  const state = { command: ['/opt/lcu/current/bin/lcu', '--audio', '--chrome'] };
  const ok = (argv) => ({ args: argv, returncode: 0, stdout: '', stderr: '' });
  const configure = (name, { scope = 'user', run = ok, executable = '/bin/omp', env = {} } = {}) => {
    const saved = { ...harness.internals };
    Object.assign(harness.internals, { which: () => executable, run });
    try {
      const environ = { PATH: '/bin', HOME: home, ...env };
      const options = { scope, project: scope === 'project' ? project : null, env: environ };
      if (name === 'omp') return harness.configure_omp(home, state.command, release, options);
      return harness.configure_hermes(home, state.command, '/original/node', release, options);
    } finally {
      Object.assign(harness.internals, saved);
    }
  };
  return { root, home, project, release, state, configure };
}

test('omp native link preserves scope and command without a skill', (t) => {
  const { home, project, release, state, configure } = fixture(t);
  const calls = [];
  const run = (argv, options) => {
    calls.push([argv, options]);
    return { args: argv, returncode: 0, stdout: '', stderr: '' };
  };
  for (const profile of ['blue', 'green']) {
    configure('omp', { run, env: { OMP_PROFILE: profile } });
    const [argv, options] = calls.at(-1);
    assert.deepEqual(argv.slice(0, 3), ['/bin/omp', 'plugin', 'link']);
    const pkg = argv[3];
    const manifest = JSON.parse(readFileSync(nat(`${pkg}/package.json`), 'utf8'));
    assert.deepEqual(manifest.omp.extensions, ['./index.ts']);
    const wrapper = readFileSync(nat(`${pkg}/index.ts`), 'utf8');
    const specifier = JSON.parse(wrapper.split('import lcu from ')[1].split(';')[0]);
    assert.ok(specifier.startsWith('.'));
    assert.equal(realpathSync(resolve(pkg, specifier)), nat(`${release}/adapters/pi/index.ts`));
    assert.ok(wrapper.includes('["/opt/lcu/current/bin/lcu", "--audio", "--chrome"]'));
    assert.ok(wrapper.includes('connectOnLoad: true'));
    assert.ok(wrapper.includes('ompEssentialTools: true'));
    assert.equal(existsSync(nat(`${pkg}/skills`)), false);
    assert.equal(options.cwd, home);
    assert.equal(options.env.HOME, home);
    assert.equal(options.timeout, 120000);
    assert.equal(options.stdin, 'devnull');
    // Exact generated bytes (Python json.dumps(manifest, indent=2) + '\n'; the ownership marker).
    assert.equal(readFileSync(nat(`${pkg}/package.json`), 'utf8'),
      '{\n  "name": "lcu-computer-use",\n  "version": "0.1.0",\n  "private": true,\n  "type": "module",\n' +
      '  "omp": {\n    "extensions": [\n      "./index.ts"\n    ]\n  }\n}\n');
    assert.equal(readFileSync(nat(`${pkg}/.lcu-generated.json`), 'utf8'), '{"harness": "omp"}\n');
  }
  assert.notEqual(calls[0][0].at(-1), calls[1][0].at(-1));
  assert.equal(existsSync(nat(`${project}/.pi`)), false);
  void state;
});

