test('failed reinstallation restores previous package', (t) => {
  const { home, state, configure } = fixture(t);
  configure('hermes', { executable: '/bin/hermes' });
  const pkg = nat(`${home}/.hermes/plugins/lcu-cua`);
  const previous = walk(pkg);
  state.command = ['/changed/runtime'];
  assert.throws(() => configure('hermes', { executable: '/bin/hermes', run: (argv) => ({ args: argv, returncode: 1, stdout: '', stderr: 'enable failed' }) }),
    { message: /enable failed/ });
  assert.deepEqual(walk(pkg), previous);
  // No staging directory is left beside the package.
  assert.deepEqual(readdirSync(nat(`${home}/.hermes/plugins`)), ['lcu-cua']);
});

test('failed package swap restores previous package', (t) => {
  const { home, configure } = fixture(t);
  configure('hermes', { executable: '/bin/hermes' });
  const pkg = nat(`${home}/.hermes/plugins/lcu-cua`);
  const previous = readFileSync(nat(`${pkg}/lcu-config.json`));
  const saved = harness.internals.replace;
  harness.internals.replace = (source, target) => {
    if (source.split(/[\\/]/).at(-1) === 'next') throw new Error('fixture rename failure');
    return saved(source, target);
  };
  try {
    assert.throws(() => configure('hermes', { executable: '/bin/hermes' }), { message: /fixture rename failure/ });
  } finally {
    harness.internals.replace = saved;
  }
  assert.deepEqual(readFileSync(nat(`${pkg}/lcu-config.json`)), previous);
});

